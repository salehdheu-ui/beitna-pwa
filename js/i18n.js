let lang = (() => {
  try {
    const saved = localStorage.getItem(K_LANG);
    if (saved && STR[saved]) return saved;
  } catch { /* تجاهل */ }
  return 'ar';
})();

export const currentLang = () => lang;
export const langInfo = (code = lang) => LANGS.find((l) => l.code === code) || LANGS[0];

/** الترجمة — ترجع العربية إن نقص المفتاح، والمفتاح نفسه إن غاب تمامًا */
export function t(key) {
  return STR[lang]?.[key] ?? STR.ar[key] ?? key;
}

export function setLang(code) {
  if (!STR[code]) return;
  lang = code;
  try { localStorage.setItem(K_LANG, code); } catch { /* تجاهل */ }
  applyLangToDocument();
}

/** يضبط اتجاه الصفحة ولغتها — العربية يمنى وما عداها يسرى */
export function applyLangToDocument() {
  const info = langInfo();
  const el = document.documentElement;
  el.lang = info.code;
  el.dir = info.dir;
  el.dataset.lang = info.code;
}
