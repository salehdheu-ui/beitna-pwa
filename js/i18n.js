let lang = (() => {
  try {
    const saved = localStorage.getItem(K_LANG);
    if (saved && STR[saved]) return saved;
  } catch { /* تجاهل */ }
  return 'ar';
})();

export const currentLang = () => lang;
export const langInfo = (code = lang) => LANGS.find((l) => l.code === code) || LANGS[0];

/** الترجمة — ترجع العربية إن نقص المفتاح، والمفتاح نفسه إن غاب تمامًا */
export function t(key) {
  return STR[lang]?.[key] ?? AUTH[lang]?.[key] ?? SYSTEM[lang]?.[key]
    ?? STR.ar[key] ?? AUTH.ar[key] ?? SYSTEM.ar[key] ?? key;
}

/** يعرض محتوى العاملة بالنسخة المحفوظة للغة المستخدم، مع رجوع آمن للأصل. */
export function localizedText(item, field) {
  const translated = item?.translations?.[lang]?.[field];
  return typeof translated === 'string' && translated.trim()
    ? translated
    : String(item?.[field] ?? '');
}

export function setLang(code) {
  if (!STR[code]) return;
  lang = code;
  try { localStorage.setItem(K_LANG, code); } catch { /* تجاهل */ }
  applyLangToDocument();
}

/** يضبط اتجاه الصفحة ولغتها — العربية يمنى وما عداها يسرى */
export function applyLangToDocument() {
  const info = langInfo();
  const el = document.documentElement;
  el.lang = info.code;
  el.dir = info.dir;
  el.dataset.lang = info.code;
  document.title = `${t('app_name')} — ${t('tagline')}`;
  document.querySelector('meta[name="description"]')?.setAttribute('content', `${t('app_name')} — ${t('tagline')}`);
  document.querySelector('#sidenav')?.setAttribute('aria-label', t('nav_more'));
  document.querySelector('#bottomnav')?.setAttribute('aria-label', t('nav_more'));
}

